func TestServeDNS_ResolvesFromPeers(t *testing.T) {
	host := "app.corpplatform.intranet"
	peers := &fakePeerSource{
		synced: true,
		peers:  map[string][]Peer{host: {{Name: "eu", IP: "10.0.0.1"}, {Name: "us", IP: "10.0.0.2"}}},
	}
	// Every authoritative peer serves the same fully-aggregated target set, so
	// the first non-empty answer is complete. Both peers return the same set.
	q := &fakeQuerier{results: map[string][]string{
		host + "|10.0.0.1": {"192.168.1.10", "192.168.1.11"},
		host + "|10.0.0.2": {"192.168.1.10", "192.168.1.11"},
	}}
	s := newTestReactive(peers, q)
	rec := dnstest.NewRecorder(&test.ResponseWriter{})

	code, err := s.ServeDNS(context.Background(), rec, query(host, dns.TypeA))
	if err != nil || code != dns.RcodeSuccess {
		t.Fatalf("unexpected code=%d err=%v", code, err)
	}
	if rec.Msg == nil || rec.Msg.Rcode != dns.RcodeSuccess {
		t.Fatalf("expected success answer, got %+v", rec.Msg)
	}
	if len(rec.Msg.Answer) != 2 {
		t.Fatalf("expected 2 A records, got %d: %+v", len(rec.Msg.Answer), rec.Msg.Answer)
	}
	// Early return: only the first (shuffled) peer that answers is queried.
	if got := atomic.LoadInt32(&q.calls); got != 1 {
		t.Fatalf("expected early return after 1 peer query, got %d", got)
	}
}

func TestServeDNS_EarlyReturn_SkipsDownPeer(t *testing.T) {
	host := "app.corpplatform.intranet"
	peers := &fakePeerSource{
		synced: true,
		peers:  map[string][]Peer{host: {{Name: "eu", IP: "10.0.0.1"}, {Name: "us", IP: "10.0.0.2"}}},
	}
	// Only one peer has the host; the other returns empty (miss/down). Regardless
	// of shuffle order, we must still resolve by falling through to the peer that
	// answers, and never call more than the two peers.
	q := &fakeQuerier{results: map[string][]string{host + "|10.0.0.2": {"192.168.1.10"}}}
	s := newTestReactive(peers, q)
	rec := dnstest.NewRecorder(&test.ResponseWriter{})

	code, _ := s.ServeDNS(context.Background(), rec, query(host, dns.TypeA))
	if code != dns.RcodeSuccess || rec.Msg == nil || len(rec.Msg.Answer) != 1 {
		t.Fatalf("expected 1 A record resolved via the answering peer, got code=%d msg=%+v", code, rec.Msg)
	}
	if got := atomic.LoadInt32(&q.calls); got < 1 || got > 2 {
		t.Fatalf("expected between 1 and 2 peer queries, got %d", got)
	}
}

