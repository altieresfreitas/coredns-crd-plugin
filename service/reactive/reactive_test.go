// fakePeerSource is an injectable PeerSource for tests.
type fakePeerSource struct {
	synced bool
	peers  map[string][]Peer
}

func (f *fakePeerSource) HasSynced() bool { return f.synced }

func (f *fakePeerSource) PeersForHost(host string) []Peer { return f.peers[host] }

// fakeQuerier is an injectable Querier for tests. It records the fqdns queried.
type fakeQuerier struct {
	results map[string][]string // key: "fqdn|peerIP" -> ips
	calls   int32
}

func (f *fakeQuerier) Query(_ context.Context, fqdn string, peer Peer) []string {
	atomic.AddInt32(&f.calls, 1)
	return f.results[fqdn+"|"+peer.IP]
}

func newTestReactive(peers PeerSource, q Querier) *Reactive {
	s := NewReactive(Opts{}, peers)
	s.querier = q
	return s
}

func query(host string, qtype uint16) *dns.Msg {
	m := new(dns.Msg)
	m.SetQuestion(dns.Fqdn(host), qtype)
	return m
}

func TestServeDNS_Passthrough_WhenAnswerPresent(t *testing.T) {
	q := &fakeQuerier{}
	s := newTestReactive(&fakePeerSource{synced: true}, q)

	r := query("app.corpplatform.intranet", dns.TypeA)
	r.Answer = append(r.Answer, test.A("app.corpplatform.intranet. 30 IN A 1.2.3.4"))
	rec := dnstest.NewRecorder(&test.ResponseWriter{})

	code, err := s.ServeDNS(context.Background(), rec, r)
	if err != nil || code != dns.RcodeSuccess {
		t.Fatalf("unexpected code=%d err=%v", code, err)
	}
	if atomic.LoadInt32(&q.calls) != 0 {
		t.Fatalf("querier should not be called on passthrough, got %d calls", q.calls)
	}
	if rec.Msg != nil {
		t.Fatalf("reactive must not write when an answer is already present")
	}
}

